"""Write NAMES.md: the game's internal names (used in every settings file) next to the names you see in game.

    python tools/names_legend.py

Two tables: every enchantment (internal name, in-game name, the gear it rolls on, whether copies on one item add
up - StackNotes.toml) and every weapon, bow and armor (the id used in Bonus.toml, Builtins.toml and
SequelGear.toml, and its in-game name). Built from the mod's own lookup tables, so it stays in step with them.
"""
import json
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools"))
import change_sheet as cs  # noqa: E402
import settings  # noqa: E402

IDS = json.loads((ROOT / "tools" / "enchant_ids.json").read_text())
POOLS = json.loads((ROOT / "tools" / "enchant_pools.json").read_text())
REGISTRY = json.loads((ROOT / "tools" / "item_registry.json").read_text())
STACK = tomllib.loads((settings.path("StackNotes.toml")).read_text(encoding="utf-8"))
CATEGORY = {"MeleeWeapons": "Melee", "RangedWeapons": "Ranged", "Armor": "Armor"}


def stacking(name):
    if name in STACK.get("full", []):
        return "adds up"
    if name in STACK.get("partly", {}):
        return "partly: " + (STACK["partly"][name] or "")
    if name in STACK.get("none", {}):
        return "no gain" + (f": {STACK['none'][name]}" if STACK["none"][name] else "")
    return ""


def main():
    L = ["# Name legend", "",
         "The settings files use the game's internal names. This lists them next to the names you see in game.",
         "Generated by `python tools/names_legend.py` from the mod's own lookup tables.", "",
         "In `Bonus.toml` a name ending in `!` means a second copy of an enchantment the item already has built in.", "",
         "## Enchantments", "",
         "| Internal name | In game | Rolls on | Two copies on one item |", "|---|---|---|---|"]
    for name in sorted(IDS, key=str.lower):
        if name in ("Unset", "Last", "EEnchantmentTypeID_MAX") or name.endswith("Idle"):
            continue                       # placeholders in the game's list, not enchantments
        gear = [g for g in ("melee", "ranged", "armor") if name in POOLS.get(g, [])]
        where = ", ".join(gear) + (" (soul gear)" if name in POOLS.get("soul", []) else "") if gear else "not rolled on gear (built-ins, mobs)"
        L.append(f"| `{name}` | {cs.ench(name)} | {where} | {stacking(name)} |")
    L += ["", "## Weapons, bows and armor", "",
          "| Id | In game | Type |", "|---|---|---|"]
    for key in sorted(REGISTRY, key=lambda k: (CATEGORY.get(k.split("/")[0], k), k.lower())):
        cat, item = key.split("/")
        if cat not in CATEGORY:
            continue
        L.append(f"| `{item}` | {cs.item(key)} | {CATEGORY[cat]} |")
    out = ROOT / "NAMES.md"
    out.write_text("\n".join(L) + "\n", encoding="utf-8")
    print(f"wrote {out} ({len(IDS)} enchantments, {sum(1 for k in REGISTRY if k.split('/')[0] in CATEGORY)} items)")


if __name__ == "__main__":
    main()
